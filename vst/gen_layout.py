#!/usr/bin/env python3
"""Writes params.json and layout.conf for Cadenza (run by hand after a change; both files are committed).
The parameter ORDER is the VST index: append new parameters at the end, never reorder (saved projects
and Q-Link maps store values by index)."""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
LANES = ["Groove", "Rolling", "Sub", "Arp", "Melody", "Pad", "Lead"]
ROOTS = ["C", "C#", "D", "Eb", "E", "F", "F#", "G", "Ab", "A", "Bb", "B"]
SCALES = ["MINOR", "MAJOR", "DORIAN", "PHRYGIAN", "MIXOLYD", "LYDIAN", "HARM MIN", "GOA PHRYG"]

params = [
    {"key": "key", "name": "Key", "options": ROOTS, "default": "A"},
    {"key": "scale", "name": "Scale", "options": SCALES, "default": "MINOR"},
    {"key": "style", "name": "Style", "options": ["GROOVE", "ROLLING", "SUB"], "default": "GROOVE"},
    {"key": "seed", "name": "Seed", "min": 0, "max": 9999, "default": 1, "display": "int"},
    {"key": "prog", "name": "Progression", "options": ["SEED"] + [str(i) for i in range(1, 13)], "default": "SEED"},
    {"key": "generate", "name": "Generate", "momentary": True},
    {"key": "variate", "name": "Variate", "momentary": True},
    {"key": "form", "name": "Form", "options": ["16 BARS", "INTRO", "BUILD", "PEAK", "RELEASE"], "default": "16 BARS"},
    {"key": "bass_feel", "name": "Bass Feel", "options": ["MELODIC", "HYPNOTIC", "DRIVING", "MINIMAL"], "default": "MELODIC"},
    {"key": "tempo_ref", "name": "Tempo Ref", "min": 99, "max": 160, "default": 99, "display": "string"},
    {"key": "swing", "name": "Swing", "min": 50, "max": 75, "default": 50, "unit": "%", "display": "int"},
    {"key": "gate", "name": "Gate", "min": 25, "max": 200, "default": 100, "unit": "%", "display": "int"},
    {"key": "pad_mode", "name": "Pad", "options": ["SINGLE", "CHORD"], "default": "CHORD"},
    {"key": "cc_out", "name": "CC Out", "options": ["OFF", "SWEEP", "PORTA", "BOTH"], "default": "OFF"},
    {"key": "preset", "name": "Preset", "min": 1, "max": 32, "default": 1, "display": "int"},
    {"key": "preset_load", "name": "Load", "momentary": True},
    {"key": "preset_save", "name": "Save", "momentary": True},
    {"key": "cc_ch", "name": "Control Ch", "options": ["OFF"] + [str(c) for c in range(1, 17)], "default": "16"},
    {"key": "status", "name": "Status", "min": 0, "max": 1, "display": "string", "type": "readout"},
    {"key": "chords", "name": "Chords", "min": 0, "max": 1, "display": "string", "type": "readout"},
]
for l in range(7):
    n = l + 1
    params += [
        {"key": "l%d_on" % n, "name": "On", "options": ["OFF", "ON"], "default": "ON"},
        {"key": "l%d_ch" % n, "name": "Channel", "min": 1, "max": 16, "default": n, "display": "int"},
        {"key": "l%d_oct" % n, "name": "Octave", "min": -2, "max": 2, "default": 0, "display": "string"},
        {"key": "l%d_var" % n, "name": "Variation", "min": 0, "max": 99, "default": 0, "display": "string"},
        {"key": "l%d_dice" % n, "name": "Dice", "momentary": True},
        {"key": "l%d_pat" % n, "name": "Steps", "min": 0, "max": 1, "display": "string", "type": "readout"},
    ]
json.dump({"name": "Cadenza", "params": params}, open(os.path.join(HERE, "params.json"), "w"), indent=1)

# ---- skin layout (shadow_page.conf syntax, see mpc-vst-plugins docs/SKIN_STUDIO.md) ----
# Palette: deep night blue chassis, warm ivory ink, a Goa-ish magenta accent.
out = ["""# Cadenza MPC skin layout. Tabs: MAIN (key, scale, style, seed, progression, generate/variate, form,
# chords + status, the current bar of all 7 lanes as text), LANES 1-4 / LANES 5-7 (on, channel, octave,
# variation, dice, steps per lane), FEEL (bass feel, tempo ref, swing, gate, pad, CC out), PRESETS.
# Q-Links carry knobs only (no switches). Generated by gen_layout.py.
style=td3
theme_bg=181a24
theme_panel=181a24
theme_line=07080c
theme_ink=ece6da
theme_ink_dim=9c98a6
theme_ink_faint=5e5b68
theme_accent=e05ad0
theme_accent_hi=f29be8
theme_knob_face=2a2d3a
theme_knob_ring=050507
theme_bar=e05ad0
theme_seg_active=e05ad0
theme_seg_inactive=2a2d3a
theme_seg_active_tx=1a0a18
theme_btn_text=1a0a18
theme_well=07080c
theme_knob_off=474a58
theme_tab_on=e05ad0
theme_tab_on_tx=1a0a18
theme_lcd=07080c
theme_box=222532
theme_btn_bg=ece6da
theme_chrome_ink=ece6da
theme_go_on=7ad34d
theme_go_off=ff6b4a
theme_tabs=e05ad0
"""]
out += ["[tab MAIN]",
        'frame x=36 y=88 w=1207 h=232 title="-" caption="CADENZA"',
        'knob cx=95 cy=200 r=40 label="KEY" key=key',
        'knob cx=220 cy=200 r=40 label="SCALE" key=scale',
        'knob cx=345 cy=200 r=40 label="STYLE" key=style',
        'knob cx=470 cy=200 r=40 label="SEED" key=seed',
        'button cx=610 cy=168 label="GENERATE" key=generate',
        'button cx=610 cy=236 label="VARIATE" key=variate',
        'knob cx=750 cy=200 r=40 label="PROG" key=prog',
        'knob cx=875 cy=200 r=40 label="FORM" key=form',
        'readout cx=1098 cy=200 w=264 h=40 label="-" caption="CHORDS" key=chords',
        'frame x=36 y=330 w=1207 h=382 title="-" caption="CURRENT BAR"']
for l in range(7):   # two columns: lanes 1-4 left, 5-7 right; the label sits above each line
    out.append('readout cx=%d cy=%d w=560 h=40 label="-" caption="%d %s" key=l%d_pat' % (
        340 if l < 4 else 940, 420 + (l % 4) * 80, l + 1, LANES[l].upper(), l + 1))
out.append('readout cx=940 cy=660 w=560 h=40 label="-" caption="STATUS" key=status')
out.append('qlinks "MAIN" = key,scale,style,seed,prog,form,swing,gate')

for t, lanes in (("LANES 1-4", range(0, 4)), ("LANES 5-7", range(4, 7))):
    out += ["[tab %s]" % t, 'frame x=36 y=88 w=1207 h=624 title="-" caption="%s"' % t]
    for k, l in enumerate(lanes):
        n = l + 1
        cy = 172 + k * 145   # one row per lane; the lane's name is its ON switch's label
        out += ['toggle cx=120 cy=%d label="%d %s" key=l%d_on' % (cy, n, LANES[l].upper(), n),
                'knob cx=290 cy=%d r=32 label="CHANNEL" key=l%d_ch' % (cy, n),
                'knob cx=410 cy=%d r=32 label="OCTAVE" key=l%d_oct' % (cy, n),
                'knob cx=530 cy=%d r=32 label="VARIATION" key=l%d_var' % (cy, n),
                'button cx=660 cy=%d label="DICE" key=l%d_dice' % (cy, n),
                'readout cx=975 cy=%d w=470 h=40 label="-" caption="STEPS" key=l%d_pat' % (cy, n)]
    out.append('qlinks "%s" = %s' % (t.replace("LANES", "LN"), ",".join(
        "l%d_oct,l%d_var" % ((l + 1,) * 2) for l in lanes)))

out += ["[tab FEEL]",
        'frame x=36 y=88 w=1207 h=624 title="-" caption="FEEL"',
        'knob cx=150 cy=260 r=48 label="BASS FEEL" key=bass_feel',
        'knob cx=340 cy=260 r=48 label="TEMPO REF" key=tempo_ref',
        'knob cx=530 cy=260 r=48 label="SWING" key=swing',
        'knob cx=720 cy=260 r=48 label="GATE" key=gate',
        'knob cx=910 cy=260 r=48 label="PAD" key=pad_mode',
        'knob cx=1100 cy=260 r=48 label="CC OUT" key=cc_out',
        'readout cx=640 cy=480 w=900 h=40 label="-" caption="STATUS" key=status',
        'qlinks "FEEL" = bass_feel,tempo_ref,swing,gate,pad_mode,cc_out']
out += ["[tab PRESETS]",
        'frame x=36 y=88 w=1207 h=624 title="-" caption="PRESETS"',
        'knob cx=200 cy=260 r=54 label="PRESET" key=preset',
        'button cx=420 cy=260 label="LOAD" key=preset_load',
        'button cx=580 cy=260 label="SAVE" key=preset_save',
        'knob cx=1040 cy=260 r=54 label="CONTROL CH" key=cc_ch',
        'readout cx=640 cy=480 w=900 h=40 label="-" caption="STATUS" key=status',
        'qlinks "PRESETS" = preset,cc_ch']
open(os.path.join(HERE, "layout.conf"), "w").write("\n".join(out) + "\n")
print("params.json: %d params, layout.conf written" % len(params))
